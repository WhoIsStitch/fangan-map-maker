function parse(txt) {
  const rows = txt.split('\n').map((r) => r.replace(/\s+$/, '')).filter((r) => r.length);
  const w = Math.max(...rows.map((r) => r.length));
  return { w, h: rows.length, rows: rows.map((r) => r.padEnd(w, '.')) };
}

export const ICONS = {};
for (const [k, v] of Object.entries(RAW)) ICONS[k] = parse(v);
ICONS.down = { ...ICONS.up, rows: [...ICONS.up.rows].reverse() };

export const ICON_NAMES = Object.keys(ICONS);

const cache = new Map();
/** A crisp canvas of the icon, `px` screen pixels per icon pixel, in `color` (light fill uses `light`). */
export function iconCanvas(name, color = '#3a2320', light = 'rgba(255,255,255,.55)', px = 4) {
  const key = name + color + light + px;
  if (cache.has(key)) return cache.get(key);
  const ic = ICONS[name];
  if (!ic) return null;
  const c = document.createElement('canvas');
  c.width = ic.w * px; c.height = ic.h * px;
  const g = c.getContext('2d');
  for (let y = 0; y < ic.h; y++) for (let x = 0; x < ic.w; x++) {
    const ch = ic.rows[y][x];
    if (ch === '#') g.fillStyle = color;
    else if (ch === '+') g.fillStyle = light;
    else continue;
    g.fillRect(x * px, y * px, px, px);
  }
  cache.set(key, c);
  return c;
}

/** Loaded <img> elements for project assets, keyed by asset id. */
const imgCache = new Map();
export function assetImage(project, id, onload) {
  const a = project.assets[id];
  if (!a) return null;
  let rec = imgCache.get(id);
  if (rec && rec.src === a.data) return rec.img.complete && rec.img.naturalWidth ? rec.img : null;
  const img = new Image();
  img.onload = () => onload && onload();
  img.src = a.data;
  imgCache.set(id, { img, src: a.data });
  return img.complete && img.naturalWidth ? img : null;
}
